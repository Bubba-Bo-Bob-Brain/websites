const ERA_INFO = [
    {
        title: "THE DAWN OF GODS",
        desc: "Immortal progenitors carve the primary mountain ranges. Magic flows as physical rivers of liquid starlight."
    },
    {
        title: "THE BRONZE HEGEMONY",
        desc: "Great empires rise. Foundries hum day and night, charting the skies and securing massive global trade networks."
    },
    {
        title: "THE GREAT CATACLYSM",
        desc: "The heavens fractured, collapsing the ancient world into dust, ashes, and sunken, corrupted ruins."
    }
];

class AncientAtlasApp {
    constructor() {
        this.currentEra = 0;
        this.activeRegion = "urkadesh";
        this.audioContext = null;
        this.ambientOscillator = null;
        this.ambientGainNode = null;
        this.isMuted = true;

        this.initDOMElements();
        this.initEventListeners();
        this.updateUI();
    }

    initDOMElements() {
        this.introOverlay = document.getElementById("intro-overlay");
        this.unsealTrigger = document.getElementById("unseal-trigger");
        this.appContainer = document.getElementById("app-container");
        this.ambientToggle = document.getElementById("ambient-toggle");
        
        this.timelineNodes = document.querySelectorAll(".timeline-node");
        this.timelineProgress = document.getElementById("timeline-progress");
        this.epochTitle = document.getElementById("epoch-title");
        this.epochDesc = document.getElementById("epoch-desc");

        this.toggleTradeRoutes = document.getElementById("toggle-trade-routes");
        this.toggleMythology = document.getElementById("toggle-mythology");
        this.toggleGrid = document.getElementById("toggle-grid");
        this.toggleAura = document.getElementById("toggle-aura");

        this.tradeRoutesGroup = document.getElementById("trade-routes-group");
        this.mythologyGroup = document.getElementById("mythology-group");
        this.navigationGrid = document.getElementById("navigation-grid");
        this.regionsGroup = document.getElementById("regions-group");

        this.regionPaths = document.querySelectorAll(".region-path");
        this.cityMarkers = document.querySelectorAll(".city-marker");
        this.bestiaryItems = document.querySelectorAll(".bestiary-item");

        this.loreTitle = document.getElementById("lore-title");
        this.loreQuote = document.getElementById("lore-quote");
        this.loreDescription = document.getElementById("lore-description");
        this.loreRuler = document.getElementById("lore-ruler");
        this.loreElement = document.getElementById("lore-element");
        this.loreMythIcon = document.getElementById("lore-myth-icon");
        this.loreMythTitle = document.getElementById("lore-myth-title");
        this.loreMythDesc = document.getElementById("lore-myth-desc");
        this.relicArt = document.getElementById("relic-art");
        this.relicName = document.getElementById("relic-name");
        this.relicDescription = document.getElementById("relic-description");
        this.loreResource = document.getElementById("lore-resource");
        this.loreWealthBar = document.getElementById("lore-wealth-bar");
        this.loreCaravans = document.getElementById("lore-caravans");
        this.loreAlliances = document.getElementById("lore-alliances");

        this.tabBtns = document.querySelectorAll(".tab-btn");
        this.tabContents = document.querySelectorAll(".tab-content");
    }

    initEventListeners() {
        this.unsealTrigger.addEventListener("click", () => this.unsealArchive());
        this.ambientToggle.addEventListener("click", () => this.toggleAmbientAudio());

        this.timelineNodes.forEach(node => {
            node.addEventListener("click", (e) => {
                const targetNode = e.currentTarget;
                const selectedEra = parseInt(targetNode.getAttribute("data-era"));
                this.shiftEra(selectedEra);
            });
        });

        this.toggleTradeRoutes.addEventListener("change", (e) => {
            this.tradeRoutesGroup.style.opacity = e.target.checked ? "1" : "0";
        });

        this.toggleMythology.addEventListener("change", (e) => {
            this.mythologyGroup.style.opacity = e.target.checked ? "1" : "0";
        });

        this.toggleGrid.addEventListener("change", (e) => {
            this.navigationGrid.style.opacity = e.target.checked ? "1" : "0";
        });

        this.toggleAura.addEventListener("change", (e) => {
            const opacityVal = e.target.checked ? "1" : "0.3";
            this.regionPaths.forEach(path => path.style.strokeOpacity = opacityVal);
        });

        this.regionPaths.forEach(path => {
            path.addEventListener("click", (e) => {
                const region = e.currentTarget.getAttribute("data-region");
                this.selectRegion(region);
            });
        });

        this.cityMarkers.forEach(marker => {
            marker.addEventListener("click", (e) => {
                const region = e.currentTarget.getAttribute("data-region");
                this.selectRegion(region);
            });
        });

        this.tabBtns.forEach(btn => {
            btn.addEventListener("click", (e) => {
                this.switchTab(e.currentTarget.getAttribute("data-tab"));
            });
        });

        this.bestiaryItems.forEach(item => {
            item.addEventListener("click", (e) => {
                const target = e.currentTarget.getAttribute("data-target");
                this.focusBestiaryItem(target);
            });
        });
    }

    unsealArchive() {
        this.introOverlay.classList.add("fade-out");
        this.appContainer.classList.remove("hidden");
        this.startAmbientAudio();
    }

    startAmbientAudio() {
        try {
            const AudioContextClass = window.AudioContext || window.webkitAudioContext;
            this.audioContext = new AudioContextClass();
            
            this.ambientOscillator = this.audioContext.createOscillator();
            this.ambientGainNode = this.audioContext.createGain();

            this.ambientOscillator.type = "sine";
            this.ambientOscillator.frequency.setValueAtTime(65, this.audioContext.currentTime); // Low celestial hum
            this.ambientOscillator.detune.setValueAtTime(10, this.audioContext.currentTime);

            const filter = this.audioContext.createBiquadFilter();
            filter.type = "lowpass";
            filter.frequency.setValueAtTime(150, this.audioContext.currentTime);

            this.ambientOscillator.connect(filter);
            filter.connect(this.ambientGainNode);
            this.ambientGainNode.connect(this.audioContext.destination);

            this.ambientGainNode.gain.setValueAtTime(0, this.audioContext.currentTime);
            this.ambientOscillator.start();

            this.isMuted = false;
            this.ambientGainNode.gain.linearRampToValueAtTime(0.25, this.audioContext.currentTime + 3);
            this.ambientToggle.classList.remove("muted");
        } catch (e) {
            console.warn("Web Audio API not supported or blocked by browser security.");
        }
    }

    toggleAmbientAudio() {
        if (!this.audioContext) {
            this.startAmbientAudio();
            return;
        }

        if (this.isMuted) {
            this.ambientGainNode.gain.linearRampToValueAtTime(0.25, this.audioContext.currentTime + 0.5);
            this.isMuted = false;
            this.ambientToggle.classList.remove("muted");
        } else {
            this.ambientGainNode.gain.linearRampToValueAtTime(0, this.audioContext.currentTime + 0.5);
            this.isMuted = true;
            this.ambientToggle.classList.add("muted");
        }
    }

    shiftEra(eraIndex) {
        this.currentEra = eraIndex;

        this.timelineNodes.forEach((node, idx) => {
            if (idx === eraIndex) {
                node.classList.add("active");
            } else {
                node.classList.remove("active");
            }
        });

        const progressPercent = (eraIndex / (this.timelineNodes.length - 1)) * 100;
        this.timelineProgress.style.width = `${progressPercent}%`;

        this.epochTitle.textContent = ERA_INFO[eraIndex].title;
        this.epochDesc.textContent = ERA_INFO[eraIndex].desc;

        this.updateUI();
        this.playEraTransitionSound();
    }

    playEraTransitionSound() {
        if (this.audioContext && !this.isMuted) {
            const sweepOsc = this.audioContext.createOscillator();
            const sweepGain = this.audioContext.createGain();
            
            sweepOsc.type = "triangle";
            sweepOsc.frequency.setValueAtTime(80, this.audioContext.currentTime);
            sweepOsc.frequency.exponentialRampToValueAtTime(240, this.audioContext.currentTime + 0.8);

            sweepGain.gain.setValueAtTime(0.15, this.audioContext.currentTime);
            sweepGain.gain.exponentialRampToValueAtTime(0.01, this.audioContext.currentTime + 0.8);

            sweepOsc.connect(sweepGain);
            sweepGain.connect(this.audioContext.destination);

            sweepOsc.start();
            sweepOsc.stop(this.audioContext.currentTime + 0.8);
        }
    }

    selectRegion(regionId) {
        this.activeRegion = regionId;

        this.regionPaths.forEach(path => {
            if (path.getAttribute("data-region") === regionId) {
                path.classList.add("active-region");
            } else {
                path.classList.remove("active-region");
            }
        });

        this.updateUI();
        this.playSelectionSound();
    }

    playSelectionSound() {
        if (this.audioContext && !this.isMuted) {
            const clickOsc = this.audioContext.createOscillator();
            const clickGain = this.audioContext.createGain();

            clickOsc.type = "sine";
            clickOsc.frequency.setValueAtTime(440, this.audioContext.currentTime);
            clickOsc.frequency.exponentialRampToValueAtTime(110, this.audioContext.currentTime + 0.15);

            clickGain.gain.setValueAtTime(0.1, this.audioContext.currentTime);
            clickGain.gain.exponentialRampToValueAtTime(0.01, this.audioContext.currentTime + 0.15);

            clickOsc.connect(clickGain);
            clickGain.connect(this.audioContext.destination);

            clickOsc.start();
            clickOsc.stop(this.audioContext.currentTime + 0.15);
        }
    }

    switchTab(tabId) {
        this.tabBtns.forEach(btn => {
            if (btn.getAttribute("data-tab") === tabId) {
                btn.classList.add("active");
            } else {
                btn.classList.remove("active");
            }
        });

        this.tabContents.forEach(content => {
            if (content.id === `tab-${tabId}`) {
                content.classList.add("active");
            } else {
                content.classList.remove("active");
            }
        });
    }

    focusBestiaryItem(target) {
        this.switchTab("mythos");
        const mythMarkerId = `myth-${target}`;
        const marker = document.getElementById(mythMarkerId);
        
        if (marker) {
            marker.scrollIntoView({ behavior: 'smooth', block: 'center' });
            
            let originalScale = marker.getAttribute("transform");
            marker.setAttribute("transform", `${originalScale} scale(1.4)`);
            setTimeout(() => {
                marker.setAttribute("transform", originalScale);
            }, 800);
        }
    }

    updateUI() {
        const regionData = LORE_DATABASE[this.activeRegion];
        if (!regionData) return;

        const eraData = regionData.eras[this.currentEra];
        if (!eraData) return;

        this.loreTitle.textContent = `${this.activeRegion.replace("-", " ").toUpperCase()}`;
        this.loreQuote.textContent = `"${eraData.quote}"`;
        this.loreDescription.textContent = eraData.description;
        this.loreRuler.textContent = eraData.ruler;
        this.loreElement.textContent = eraData.element;

        this.loreMythIcon.textContent = eraData.mythIcon;
        this.loreMythTitle.textContent = eraData.mythTitle;
        this.loreMythDesc.textContent = eraData.mythDesc;

        this.relicArt.textContent = eraData.relicIcon;
        this.relicName.textContent = eraData.relicName;
        this.relicDescription.textContent = eraData.relicDesc;

        this.loreResource.textContent = eraData.resource;
        this.loreWealthBar.style.width = eraData.wealth;
        this.loreCaravans.textContent = eraData.caravans;

        this.loreAlliances.innerHTML = "";
        eraData.alliances.forEach(alliance => {
            const li = document.createElement("li");
            li.textContent = alliance;
            this.loreAlliances.appendChild(li);
        });

        const activeRegionPath = document.querySelector(`[data-region="${this.activeRegion}"]`);
        if (activeRegionPath && !activeRegionPath.classList.contains("active-region")) {
            this.regionPaths.forEach(path => path.classList.remove("active-region"));
            activeRegionPath.classList.add("active-region");
        }
    }
}

document.addEventListener("DOMContentLoaded", () => {
    window.AncientAtlas = new AncientAtlasApp();
});