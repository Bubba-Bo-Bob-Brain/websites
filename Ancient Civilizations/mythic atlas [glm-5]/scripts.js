    startCaravanAnimations: function() {
        const routes = document.querySelectorAll('.trade-route');
        const caravanElements = document.querySelectorAll('.caravan');
        const routePaths = Array.from(routes);

        this.caravans = Array.from(caravanElements).map(function(caravan, index) {
            const routeIndex = index % routePaths.length;
            const path = routePaths[routeIndex];
            return {
                element: caravan,
                path: path,
                progress: Math.random(),
                speed: 0.001 + Math.random() * 0.002,
                direction: Math.random() > 0.5 ? 1 : -1
            };
        });

        this.animateCaravans();
    },

    animateCaravans: function() {
        App.caravans.forEach(function(caravan) {
            caravan.progress += caravan.speed * caravan.direction;
            if (caravan.progress >= 1) {
                caravan.direction = -1;
                caravan.progress = 1;
            } else if (caravan.progress <= 0) {
                caravan.direction = 1;
                caravan.progress = 0;
            }

            const point = App.getPointAtLength(caravan.path, caravan.progress);
            if (point) {
                caravan.element.setAttribute('transform', 'translate(' + point.x + ', ' + point.y + ')');
            }
        });

        App.animationFrameId = requestAnimationFrame(App.animateCaravans);
    },

    getPointAtLength: function(pathElement, progress) {
        const pathLength = pathElement.getTotalLength();
        const point = pathElement.getPointAtLength(pathLength * progress);
        return point;
    },

