    createDustParticles: function() {
        const container = document.getElementById('dustParticles');
        if (!container) return;
        const particleCount = 40;
        for (let i = 0; i < particleCount; i++) {
            const particle = document.createElement('div');
            particle.className = 'dust-particle';
            particle.style.left = Math.random() * 100 + '%';
            particle.style.top = Math.random() * 100 + '%';
            particle.style.animationDelay = Math.random() * 20 + 's';
            particle.style.animationDuration = (15 + Math.random() * 10) + 's';
            const size = 2 + Math.random() * 4;
            particle.style.width = size + 'px';
            particle.style.height = size + 'px';
            container.appendChild(particle);
        }
    },

    setupTimeline: function() {
        const markers = document.querySelectorAll('.era-marker');
        const sliderHandle = document.getElementById('sliderHandle');
        const currentEraDisplay = document.getElementById('currentEra');
        const slider = document.getElementById('timelineSlider');

        markers.forEach(function(marker, index) {
            marker.addEventListener('click', function() {
                const era = marker.dataset.era;
                App.setEra(era);
                App.updateSliderPosition(index);
                markers.forEach(function(m) { m.classList.remove('active'); });
                marker.classList.add('active');
                currentEraDisplay.textContent = marker.querySelector('.era-name').textContent;
            });
        });

        let isDraggingSlider = false;

        sliderHandle.addEventListener('mousedown', function(e) {
            isDraggingSlider = true;
            e.preventDefault();
        });

        document.addEventListener('mousemove', function(e) {
            if (!isDraggingSlider) return;
            const rect = slider.getBoundingClientRect();
            let position = (e.clientX - rect.left) / rect.width;
            position = Math.max(0, Math.min(1, position));
            const eraIndex = Math.round(position * 3);
            App.updateSliderPosition(eraIndex);
            const era = markers[eraIndex].dataset.era;
            App.setEra(era);
            markers.forEach(function(m) { m.classList.remove('active'); });
            markers[eraIndex].classList.add('active');
            currentEraDisplay.textContent = markers[eraIndex].querySelector('.era-name').textContent;
        });

        document.addEventListener('mouseup', function() {
            isDraggingSlider = false;
        });

        markers[1].classList.add('active');
    },

    updateSliderPosition: function(index) {
        const sliderHandle = document.getElementById('sliderHandle');
        const position = (index / 3) * 100;
        sliderHandle.style.left = position + '%';
    },

    setEra: function(era) {
        this.currentEra = era;
        this.updateEraBorders();
        this.updateInfoPanelForEra();
    },

    updateEraBorders: function() {
        const eraBorders = document.querySelectorAll('.era-border');
        eraBorders.forEach(function(border) { border.classList.remove('active'); });
    },

    updateInfoPanelForEra: function() {
        if (this.selectedRegion) {
            this.showRegionInfo(this.selectedRegion);
        }
    },

    setupRegions: function() {
        const regions = document.querySelectorAll('.region');
        regions.forEach(function(region) {
            region.addEventListener('click', function(e) {
                e.stopPropagation();
                const civId = region.dataset.civ;
                App.selectRegion(region, civId);
            });
            region.addEventListener('mouseenter', function() {
                const civId = region.dataset.civ;
                App.highlightLegendItem(civId);
            });
            region.addEventListener('mouseleave', function() {
                const civId = region.dataset.civ;
                App.unhighlightLegendItem(civId);
            });
        });
    },

    selectRegion: function(regionElement, civId) {
        document.querySelectorAll('.region').forEach(function(r) { r.classList.remove('selected'); });
        regionElement.classList.add('selected');
        this.selectedRegion = civId;
        this.showRegionInfo(civId);
    },

    showRegionInfo: function(civId) {
        const civ = AtlasLore.civilizations[civId];
        const infoContent = document.getElementById('infoContent');
        const eraData = civ.eraData[this.currentEra];

        let tradeGoodsHtml = '';
        civ.trade.forEach(function(good) {
            tradeGoodsHtml += '<span class="trade-good">' + good + '</span>';
        });

        infoContent.innerHTML = 
            '<div class="region-info">' +
                '<h3 class="info-title">' + civ.name + '</h3>' +
                '<div class="info-divider"></div>' +
                '<div class="info-era-status">' +
                    '<span class="era-badge">' + this.formatEraName(this.currentEra) + '</span>' +
                    '<span class="status-badge">' + eraData.status + '</span>' +
                '</div>' +
                '<div class="info-section">' +
                    '<h4>Territories</h4>' +
                    '<p>' + eraData.borders + '</p>' +
                '</div>' +
                '<div class="info-section">' +
                    '<h4>Capital</h4>' +
                    '<p>' + civ.capital + '</p>' +
                '</div>' +
                '<div class="info-section">' +
                    '<h4>Key Trade Goods</h4>' +
                    '<div class="trade-goods">' + tradeGoodsHtml + '</div>' +
                '</div>' +
                '<button class="lore-button" data-civ="' + civId + '">View Full Chronicles</button>' +
            '</div>';

        const loreButton = infoContent.querySelector('.lore-button');
        loreButton.addEventListener('click', function() {
            App.openLoreModal(civId, 'civilization');
        });
    },

